// ScrollTrigger Animations
window.addEventListener("load", function () {

    // Refresh ScrollTrigger to recalculate layout dimensions after all images/assets load
    ScrollTrigger.refresh();

    gsap.from(".about-main", {
        scrollTrigger: {
            trigger: "#about",
            start: "top 75%"
        },
        x: -120,
        opacity: 0,
        duration: 1.2
    });

    // Animate section title in About section
    gsap.from("#about .section-title", {
        scrollTrigger: {
            trigger: "#about",
            start: "top 75%"
        },
        y: 80,
        opacity: 0,
        duration: 1
    });

    // Animate section title in Services section
    gsap.from("#services .section-title", {
        scrollTrigger: {
            trigger: "#services",
            start: "top 75%"
        },
        y: 80,
        opacity: 0,
        duration: 1
    });

    gsap.from(".feature-item", {
        scrollTrigger: {
            trigger: "#about",
            start: "top 70%"
        },
        y: 40,
        opacity: 0,
        stagger: 0.2,
        duration: 1
    });

    gsap.from(".service-list-item", {
        scrollTrigger: {
            trigger: "#services",
            start: "top 75%"
        },
        opacity: 0,
        y: 40,
        stagger: 0.1,
        duration: 0.8,
        onComplete: function() {
            // Clear inline styles generated by GSAP so hover effects/height transitions in CSS work properly
            gsap.set(".service-list-item", { clearProps: "transform,opacity" });
        }
    });

    gsap.from(".sticky-image-wrapper", {
        scrollTrigger: {
            trigger: "#services",
            start: "top 75%"
        },
        opacity: 0,
        scale: 0.95,
        duration: 1,
        ease: "power2.out"
    });

    // Services Hover & Image Swapping Logic
    const serviceItems = document.querySelectorAll(".service-list-item");
    const showcaseImgs = document.querySelectorAll(".service-showcase-img");

    serviceItems.forEach((item) => {
        item.addEventListener("mouseenter", function () {
            // Remove active class from all items and images
            serviceItems.forEach((i) => i.classList.remove("active"));
            showcaseImgs.forEach((img) => img.classList.remove("active"));

            // Add active class to current item
            this.classList.add("active");

            // Add active class to corresponding image
            const serviceIndex = this.getAttribute("data-service");
            const targetImg = document.querySelector(`.service-showcase-img[data-img="${serviceIndex}"]`);
            if (targetImg) {
                targetImg.classList.add("active");
            }
        });
    });

});